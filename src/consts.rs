// In the game docs:
// MINERAL_DENSITY_PROBABILITY  : {
//     1: 0.1,
//     2: 0.5,
//     3: 0.9,
//     4: 1.0
// },
// Here they are converted into actual probability value
// In the original game engine, they are generated by trying the probability of Low, and then retrying with Medium if Low fails,
// (engine/src/processor/intents/minerals/tick.js line 20)
// meaning that Medium has an actual probability of (1 - 0.1) * 0.5 = 0.45
// and High has an actual probability of (1 - 0.1) * (1 - 0.5) * 0.9 = 0.405
// and Ultra has an actual probability of (1 - 0.1) * (1 - 0.5) * (1 - 0.9) = 0.045

